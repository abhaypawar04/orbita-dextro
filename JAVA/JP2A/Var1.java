
class Var1 {

    public static void main(String[] args) {
        // integer contains only a whole numbers : 
        int age;
        age = 2;
        int year = 2026;
        System.out.println(age);
        System.out.println("this is year " + year);
//-----

        //doubles : 
        double price = 50.52;
        double temperature = 4.058;
        double gpa = 7.9;

        System.out.println(price);
        System.out.println(temperature);
        System.out.println("gpa is a " + gpa);
//-----
        //char
        char grade = 'k';
        char symbol = '@';
        char currency = '$';
        System.out.println(grade);
        System.out.println(symbol);
        System.out.println(currency);
//-----
        //boolean
        boolean b1 = true;
        boolean b2 = false;
        System.out.println(b1);
        System.out.println(b2);
//-----

        //string = series of a character;
        String email = "abhaypawar0407@gmail.com";
        String food = "apple  banana cherry";

        System.out.println("your email is a : " + email);
        System.out.println("your fruits is : " + food);
//-----
    }

}
